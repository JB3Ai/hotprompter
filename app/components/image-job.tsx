"use client";

import { useEffect, useRef } from "react";

export type ImageJob = {
  promptId: string; prompt: string; negativePrompt: string; status: string; width: number; height: number;
  image: string | null; filename: string; error: string; seed: number | null; steps: number; cfg: number; hash: string;
};

export function ImageJobDrawer({ open, onClose, job, running, onReuseSeed }: { open: boolean; onClose: () => void; job: ImageJob | null; running: boolean; onReuseSeed: (seed: number) => void }) {
  const dialog = useRef<HTMLDialogElement>(null);
  useEffect(() => {
    const element = dialog.current;
    if (!element) return;
    if (open && !element.open) element.showModal();
    if (!open && element.open) element.close();
  }, [open]);

  return (
    <dialog ref={dialog} className="sidebar-notepad image-job-drawer" aria-labelledby="image-job-title" onCancel={(event) => { event.preventDefault(); onClose(); }}>
      <div className="stack">
        <div className="row-between">
          <div><p className="eyebrow">Submitted snapshot</p><h2 id="image-job-title">Image job</h2></div>
          <button type="button" className="btn btn-small" onClick={onClose} autoFocus>Close</button>
        </div>
        {!job ? <p className="muted">No image has been submitted in this session.</p> : <>
          <div className={`job-state ${job.error ? "is-error" : job.image ? "is-ready" : "is-running"}`} role="status" aria-live="polite">
            <span className="memory-led" aria-hidden="true" /><strong>{job.error || job.status || (running ? "Working…" : "Waiting")}</strong>
          </div>
          <p className="muted small">This job uses the frozen prompt below. You can close this drawer and build the next prompt without changing it.</p>
          {job.promptId && <p className="muted small">ComfyUI ID: <code>{job.promptId}</code></p>}
          <div><h3>Prompt sent to ComfyUI</h3><pre className="prompt-pre job-prompt">{job.prompt}</pre></div>
          <details className="job-negative"><summary>Negative prompt</summary><pre className="prompt-pre job-prompt">{job.negativePrompt || "Off"}</pre></details>
          <div className="job-facts">
            <span>Output: {job.width} × {job.height}</span><span>Steps: {job.steps}</span><span>CFG: {job.cfg.toFixed(1)}</span><span>Seed: {job.seed ?? "pending"}</span>
          </div>
          {job.hash && <p className="muted small">Snapshot: <code>{job.hash}</code></p>}
          {job.seed !== null && <button type="button" className="btn btn-small" onClick={() => onReuseSeed(job.seed as number)}>Reuse this seed</button>}
          {job.image && <div className="image-preview"><img src={job.image} alt="Generated by ComfyUI" width={job.width} height={job.height} /><a href={`${job.image}&download=1`} download={job.filename} className="btn btn-primary">Download PNG</a></div>}
        </>}
      </div>
    </dialog>
  );
}
